create or replace function public.admin_set_ad_code(p_slug text, p_code text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_code   text;
  v_existed boolean;
begin
  perform public.require_admin();

  if p_slug is null or p_slug !~ '^[a-z0-9_-]{2,32}$' then
    raise exception 'Invalid placement slug (a-z, 0-9, underscore, hyphen)'
      using errcode = '22023';
  end if;

  v_code := nullif(btrim(coalesce(p_code, '')), '');

  if v_code is not null and length(v_code) > 20000 then
    raise exception 'Ad code is too long (max 20000 characters)'
      using errcode = '22023';
  end if;

  -- Refuse snippets that would destroy the page if injected after load.
  if v_code is not null and v_code ~ 'document[[:space:]]*\.[[:space:]]*write[[:space:]]*\(' then
    raise exception
      'This snippet uses document.write(), which cannot work when injected after page load and would blank the page. Ask your network for the standard script tag version.'
      using errcode = '22023';
  end if;

  select exists (select 1 from public.ad_placements where slug = p_slug)
    into v_existed;

  if not v_existed then
    raise exception 'Placement not found: %', p_slug using errcode = 'P0002';
  end if;

  update public.ad_placements
     set code = v_code, updated_at = now()
   where slug = p_slug;

  return jsonb_build_object(
    'ok', true,
    'slug', p_slug,
    'has_code', v_code is not null,
    'code_length', coalesce(length(v_code), 0)
  );
end;
$$;

-- 7.x Admin write for the two script-only ad formats.
--
-- Unlike admin_save_placement() there is no location here: a popunder and a
-- smartlink have no container. The upsert keeps a pasted snippet across
-- re-runs, and a blank p_code clears it rather than storing an empty string.
create or replace function public.admin_set_ad_script(
  p_kind    text,
  p_code    text default null,
  p_enabled boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_kind text;
  v_code text;
begin
  perform public.require_admin();

  v_kind := lower(btrim(coalesce(p_kind, '')));

  if v_kind not in ('popunder', 'smartlink') then
    raise exception
      'Invalid script kind "%". Must be popunder or smartlink.', v_kind
      using errcode = '22023';
  end if;

  v_code := nullif(btrim(coalesce(p_code, '')), '');

  if v_code is not null and length(v_code) > 20000 then
    raise exception 'Ad script is too long (max 20000 characters)'
      using errcode = '22023';
  end if;

  if v_code is not null
     and v_code ~ 'document[[:space:]]*\.[[:space:]]*write[[:space:]]*\(' then
    raise exception
      'This snippet uses document.write(), which cannot work when injected after page load and would blank the page. Ask your network for the standard script tag version.'
      using errcode = '22023';
  end if;

  -- A smartlink is a URL, not a script. Refuse anything that is obviously not
  -- one, because a malformed prefix would silently break every Exit click.
  if v_kind = 'smartlink' and v_code is not null
     and v_code !~ '^https?://' then
    raise exception
      'A smartlink must be an http:// or https:// URL. Paste the smartlink address, including any ?url= or &url= prefix your network gave you.'
      using errcode = '22023';
  end if;

  -- Refuse to enable a format that has nothing to load, so the admin panel
  -- can never show a switch that silently does nothing.
  if p_enabled and v_code is null then
    raise exception
      'Cannot enable % because no code has been saved for it yet.', v_kind
      using errcode = '22023';
  end if;

  insert into public.ad_scripts (kind, code, enabled)
  values (v_kind, v_code, coalesce(p_enabled, false))
  on conflict (kind) do update
    set code    = excluded.code,
        enabled = excluded.enabled,
        updated_at = now();

  return jsonb_build_object(
    'ok', true,
    'kind', v_kind,
    'has_code', v_code is not null,
    'code_length', coalesce(length(v_code), 0),
    'enabled', coalesce(p_enabled, false)
  );
end;
$$;

