create or replace function public.guard_profile_write()
returns trigger
language plpgsql
as $$
begin
  -- Allow the owner (postgres / service_role / SECURITY DEFINER) to proceed.
  if current_user not in ('authenticated', 'anon') then
    return new;
  end if;

  if tg_op = 'INSERT' then
    new.coins          := 0;
    new.total_taps     := 0;
    new.level          := 1;
    new.experience     := 0;
    new.highest_combo  := 0;
    new.coins_per_tap  := 1;
    return new;
  end if;

  if new.coins is distinct from old.coins
     or new.total_taps is distinct from old.total_taps
     or new.coins_per_tap is distinct from old.coins_per_tap
     or new.level is distinct from old.level
     or new.experience is distinct from old.experience
     or new.highest_combo is distinct from old.highest_combo then
    raise exception 'Protected column: progression values are updated by the server only'
      using errcode = '42501';
  end if;

  if new.username is null or btrim(new.username) = ''
     or length(new.username) > 24
     or new.username !~ '^[a-z0-9_]{3,24}$' then
    raise exception 'Invalid username: use 3-24 characters (a-z, 0-9, underscore)'
      using errcode = '22023';
  end if;

  new.display_name := left(coalesce(new.display_name, new.username), 40);
  return new;
end;
$$;

drop trigger if exists profiles_guard_write on public.profiles;
create trigger profiles_guard_write
  before insert or update on public.profiles
  for each row execute function public.guard_profile_write();

create or replace function public.guard_game_state_write()
returns trigger
language plpgsql
as $$
begin
  if current_user not in ('authenticated', 'anon') then
    return new;
  end if;

  if tg_op = 'INSERT' then
    new.combo := 0;
    return new;
  end if;

  if new.combo is distinct from old.combo
     or new.last_tap_at is distinct from old.last_tap_at
     or new.last_batch_at is distinct from old.last_batch_at
     or new.last_daily_reward is distinct from old.last_daily_reward then
    raise exception 'Protected column: combo/tap state is updated by the server only'
      using errcode = '42501';
  end if;

  return new;
end;
$$;

drop trigger if exists game_state_guard_write on public.game_state;
create trigger game_state_guard_write
  before insert or update on public.game_state
  for each row execute function public.guard_game_state_write();

-- Ad events: must reference a real, enabled placement and be rate limited.
create or replace function public.guard_ad_event()
returns trigger
language plpgsql
as $$
declare
  v_gap integer;
begin
  if not exists (
    select 1 from public.ad_placements p
    where p.slug = new.placement
  ) then
    raise exception 'Unknown ad placement: %', new.placement using errcode = '22023';
  end if;

  if not exists (
    select 1 from public.ad_placements p
    where p.slug = new.placement and p.enabled
  ) then
    raise exception 'Ad placement is disabled: %', new.placement using errcode = '22023';
  end if;

  v_gap := (public.game_limits() ->> 'ad_event_min_gap_seconds')::integer;

  -- Silently skip (return NULL => row is not inserted) anything more frequent
  -- than the network's own minimum reporting cadence.
  if exists (
    select 1 from public.ad_events e
    where e.user_id = new.user_id
      and e.placement = new.placement
      and e.created_at > now() - make_interval(secs => v_gap)
  ) then
    return null;
  end if;

  return new;
end;
$$;

drop trigger if exists ad_events_guard on public.ad_events;
create trigger ad_events_guard
  before insert on public.ad_events
  for each row execute function public.guard_ad_event();

