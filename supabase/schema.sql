create or replace function public.require_admin()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Not authenticated' using errcode = '28000';
  end if;
  if not exists (select 1 from public.admin_users au where au.user_id = auth.uid()) then
    raise exception 'Admin privileges required' using errcode = '42501';
  end if;
end;
$$;

-- Creates any missing per-user rows (self-healing, own user only).
create or replace function public.ensure_user_state(p_user uuid default auth.uid())
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_user is null or p_user <> auth.uid() then
    raise exception 'Not allowed' using errcode = '42501';
  end if;

  insert into public.profiles (id, username, display_name)
  values (p_user, 'player_' || left(replace(p_user::text, '-', ''), 8), 'Player')
  on conflict (id) do nothing;

  insert into public.game_state (user_id) values (p_user) on conflict (user_id) do nothing;
  insert into public.daily_rewards (user_id) values (p_user) on conflict (user_id) do nothing;
end;
$$;

