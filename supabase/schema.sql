-- XP required to advance FROM p_level TO p_level + 1
create or replace function public.xp_to_next(p_level integer)
returns bigint
language sql
immutable
as $$
  select (100::bigint * greatest(coalesce(p_level, 1), 1))
       + (25::bigint * (greatest(coalesce(p_level, 1), 1)::bigint * greatest(coalesce(p_level, 1), 1)));
$$;

-- 0.1 Game tuning constants (documented, enforced in process_tap)
create or replace function public.game_limits()
returns jsonb
language sql
stable
as $$
  select jsonb_build_object(
    'min_tap_interval_ms', 40,      -- fastest physically plausible tap cadence
    'max_taps_per_batch', 250,     -- hard cap accepted from a client batch
    'max_coins_per_batch', 1000000,
    'combo_window_ms', 900,        -- average interval required to sustain combo
    'max_combo', 10000,
    'min_batch_gap_ms', 25,        -- fastest accepted round trip between batches
    'ad_event_min_gap_seconds', 60
  );
$$;

