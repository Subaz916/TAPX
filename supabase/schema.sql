-- 6.3 Daily reward: one legitimate claim per 24 hours.
create or replace function public.claim_daily_reward()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user   uuid := auth.uid();
  v_d      public.daily_rewards%rowtype;
  v_streak integer;
  v_reward bigint := 0;
  v_table  jsonb;
  v_coins  bigint;
begin
  if v_user is null then
    raise exception 'Not authenticated' using errcode = '28000';
  end if;

  perform public.ensure_user_state(v_user);

  select * into v_d from public.daily_rewards where user_id = v_user for update;

  if v_d.last_claimed_at is not null and v_d.last_claimed_at > now() - interval '24 hours' then
    raise exception 'Daily reward already claimed'
      using errcode = 'P0001',
            detail = json_build_object(
              'reason', 'too_soon',
              'next_at', v_d.last_claimed_at + interval '24 hours',
              'streak', v_d.streak
            )::text;
  end if;

  select value into v_table from public.app_settings where key = 'daily_rewards';
  if v_table is null or jsonb_typeof(v_table) <> 'array' then
    v_table := '[100,150,250,400,600,800,1200]'::jsonb;
  end if;

  if v_d.last_claimed_at is null
     or v_d.last_claimed_at <= now() - interval '48 hours' then
    v_streak := 1;                     -- missed a day: streak restarts
  else
    v_streak := least(v_d.streak + 1, jsonb_array_length(v_table));
  end if;

  -- Read the configured amount defensively: never trust the shape of jsonb.
  select case
           when (v_table ->> (v_streak - 1)) ~ '^[0-9]{1,18}$'
             then (v_table ->> (v_streak - 1))::bigint
           else 0
         end
    into v_reward;

  update public.daily_rewards
     set streak = v_streak, last_claimed_at = now()
   where user_id = v_user;

  update public.profiles set coins = coins + v_reward where id = v_user
    returning coins into v_coins;

  return jsonb_build_object(
    'ok', true,
    'streak', v_streak,
    'reward', v_reward,
    'coins', v_coins,
    'next_at', now() + interval '24 hours'
  );
end;
$$;

