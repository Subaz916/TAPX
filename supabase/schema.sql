  if coalesce(p_base_cost, 0) < 1 or coalesce(p_max_level, 0) < 1
     or coalesce(p_growth, 0) <= 1 or coalesce(p_multiplier, 0) <= 0 then
    raise exception 'Invalid upgrade configuration' using errcode = '22023';
  end if;

  if p_id is null then
    insert into public.upgrades (slug, name, description, icon, base_cost, growth, multiplier, max_level, sort_order, active)
    values (p_slug, left(p_name, 60), p_description, coalesce(p_icon, 'bolt'),
            p_base_cost, p_growth, p_multiplier, p_max_level, coalesce(p_sort_order, 0), coalesce(p_active, true))
    returning id into v_id;
  else
    update public.upgrades
       set slug = p_slug, name = left(p_name, 60), description = p_description,
           icon = coalesce(p_icon, 'bolt'), base_cost = p_base_cost, growth = p_growth,
           multiplier = p_multiplier, max_level = p_max_level,
           sort_order = coalesce(p_sort_order, 0), active = coalesce(p_active, true)
     where id = p_id
    returning id into v_id;
  end if;

  return jsonb_build_object('ok', true, 'id', v_id);
end;
$$;

