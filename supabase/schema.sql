create or replace function public.admin_save_placement(
  p_id          bigint   default null,
  p_slug        text     default '',
  p_label       text     default '',
  p_location    text     default 'top',
  p_description text     default null,
  p_enabled     boolean  default true,
  p_sort_order  integer  default 0
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id       bigint;
  v_slug     text;
  v_location text;
begin
  perform public.require_admin();

  v_slug := lower(btrim(coalesce(p_slug, '')));
  v_location := lower(btrim(coalesce(p_location, 'top')));

  if v_slug !~ '^[a-z0-9_-]{2,32}$' then
    raise exception
      'Invalid slug "%". Use 2-32 characters: a-z, 0-9, underscore or hyphen. Spaces are not allowed.', v_slug
      using errcode = '22023';
  end if;

  -- Only the containers that exist in index.html. A placement pointing
  -- anywhere else would be saved but never render, so it is rejected here.
  --
  -- The hint matters: this whitelist grew from three locations to five. A
  -- database that still has the older admin_save_placement() rejects a valid
  -- location such as "stats" with this exact message, and the most likely
  -- cause is always a stale function definition rather than bad input.
  if v_location not in ('top', 'stats', 'between', 'inline', 'bottom') then
    raise exception
      'Invalid location "%". Must be top, stats, between, inline or bottom. '
      'If that location is one of those five, this database is running an '
      'outdated admin_save_placement(): re-run supabase/schema.sql, which is '
      'idempotent. Check with: select value from public.app_settings where key = ''schema_version''.',
      v_location
      using errcode = '22023';
  end if;

  if btrim(coalesce(p_label, '')) = '' then
    raise exception 'Label is required.' using errcode = '22023';
  end if;

  if exists (
    select 1 from public.ad_placements
     where location = v_location and (p_id is null or id <> p_id)
  ) then
    raise exception
      'A placement already uses the "%" container. Edit that one instead.', v_location
      using errcode = '22023';
  end if;

  if p_id is null then
    insert into public.ad_placements (slug, label, location, description, enabled, sort_order)
    values (v_slug, left(btrim(p_label), 60), v_location, p_description, coalesce(p_enabled, true), coalesce(p_sort_order, 0))
    returning id into v_id;
  else
    update public.ad_placements
       set slug = v_slug,
           label = left(btrim(p_label), 60),
           location = v_location,
           description = p_description,
           enabled = coalesce(p_enabled, true),
           sort_order = coalesce(p_sort_order, 0)
     where id = p_id
    returning id into v_id;

    if v_id is null then
      raise exception 'Placement not found' using errcode = 'P0002';
    end if;
  end if;

  return jsonb_build_object('ok', true, 'id', v_id);
end;
$$;

