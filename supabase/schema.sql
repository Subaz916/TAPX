create or replace function public.admin_save_upgrade(
  p_id          bigint   default null,
  p_slug        text     default '',
  p_name        text     default '',
  p_description text     default null,
  p_icon        text     default 'bolt',
  p_base_cost   bigint   default 100,
  p_growth      numeric  default 1.15,
  p_multiplier  numeric  default 1.15,
  p_max_level   integer  default 20,
  p_sort_order  integer  default 0,
  p_active      boolean  default true
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
begin
