-- 6.1 Register a tap batch. All rewards are computed server-side.
create or replace function public.process_tap(
  p_tap_count  integer,
  p_duration_ms integer default 0,
  p_client_combo integer default 0
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user      uuid := auth.uid();
  v_lim       jsonb := public.game_limits();
  v_min_int   integer := (v_lim ->> 'min_tap_interval_ms')::integer;
  v_max_batch integer := (v_lim ->> 'max_taps_per_batch')::integer;
  v_max_coins bigint   := (v_lim ->> 'max_coins_per_batch')::bigint;
  v_combo_win integer := (v_lim ->> 'combo_window_ms')::integer;
  v_max_combo integer := (v_lim ->> 'max_combo')::integer;
  v_min_gap   integer := (v_lim ->> 'min_batch_gap_ms')::integer;

  v_p        public.profiles%rowtype;
  v_s        public.game_state%rowtype;
  v_taps     integer;
  v_elapsed  numeric := 0;
  v_span     numeric;
  v_allowed  integer;
  v_avg      numeric;

  v_tap_power integer := 0;
  v_combo_boost integer := 0;
  v_crit      integer := 0;
  v_bonus     integer := 0;

  v_base      numeric;
  v_mult      numeric;
  v_per_tap   numeric;
  v_coins     numeric;
  v_gain      bigint;
  v_crit_hit  boolean := false;
  v_crit_chance numeric;

  v_exp       bigint;
  v_level     integer;
  v_new_combo integer;
  v_time      timestamptz := now();
begin
  if v_user is null then
    raise exception 'Not authenticated' using errcode = '28000';
  end if;

  perform public.ensure_user_state(v_user);

  -- --- validate input -------------------------------------------------------
  if p_tap_count is null or p_tap_count < 1 or p_tap_count > v_max_batch then
    raise exception 'Invalid tap count (expected 1..%)', v_max_batch using errcode = '22023';
  end if;
  v_taps := p_tap_count;
  if p_duration_ms is null or p_duration_ms < 0 or p_duration_ms > 600000 then
    p_duration_ms := 0;
  end if;

  select * into v_s from public.game_state where user_id = v_user for update;
  select * into v_p from public.profiles where id = v_user for update;

  -- Elapsed wall-clock time since the previous accepted batch.
  if v_s.last_batch_at is not null then
    v_elapsed := extract(epoch from (v_time - v_s.last_batch_at)) * 1000;
  else
    v_elapsed := 60000;
  end if;
  v_elapsed := greatest(v_elapsed, v_min_gap::numeric);

  -- Reject impossible tap density (server-side anti-abuse). The count is
  -- CLAMPED rather than rejected so that laggy clients are not punished.
  v_allowed := floor(v_elapsed / v_min_int)::integer + 2;
  if v_taps > v_allowed then
    v_taps := greatest(v_allowed, 1);
  end if;

  -- Duration used for combo math: the larger of the client-reported span and
  -- the real server-side gap (never trusts the client to make itself faster).
  v_span := greatest(p_duration_ms::numeric, v_elapsed);

  -- --- upgrade levels -------------------------------------------------------
  select
    coalesce(max(uu.level) filter (where u.slug = 'tap_power'), 0),
    coalesce(max(uu.level) filter (where u.slug = 'combo_boost'), 0),
    coalesce(max(uu.level) filter (where u.slug = 'critical_tap'), 0),
    coalesce(max(uu.level) filter (where u.slug = 'bonus_multiplier'), 0)
  into v_tap_power, v_combo_boost, v_crit, v_bonus
  from public.user_upgrades uu
  join public.upgrades u on u.id = uu.upgrade_id
  where uu.user_id = v_user;

  -- --- coin math ------------------------------------------------------------
  v_base := (v_p.coins_per_tap::numeric + (v_p.level - 1) * 0.1)
            * power(1.15, v_tap_power);
  v_mult := power(1.10, greatest(v_combo_boost, 0))
            * power(1.25, greatest(v_bonus, 0));
  v_per_tap := v_base * v_mult;

  v_coins := trunc(v_per_tap * v_taps);

  v_crit_chance := least(v_crit * 0.02, 0.30);
  if v_crit_chance > 0 and random() < v_crit_chance then
    v_coins := trunc(v_coins * 2);
    v_crit_hit := true;
  end if;

  v_gain := least(greatest(trunc(v_coins), 0), v_max_coins);

  -- --- combo ----------------------------------------------------------------
  v_avg := v_span / v_taps::numeric;
  if v_avg <= v_combo_win then
    v_new_combo := least(v_s.combo + v_taps, v_max_combo);
  else
    v_new_combo := 0;
  end if;

  -- --- xp / level -----------------------------------------------------------
  v_exp := v_p.experience + v_taps + floor(v_gain / 2);
  v_level := v_p.level;
  while v_exp >= public.xp_to_next(v_level) and v_level < 1000 loop
    v_exp := v_exp - public.xp_to_next(v_level);
    v_level := v_level + 1;
  end loop;

  -- --- persist --------------------------------------------------------------
  update public.profiles
     set coins = coins + v_gain,
         total_taps = total_taps + v_taps,
         experience = v_exp,
         level = v_level,
         highest_combo = greatest(highest_combo, v_new_combo)
   where id = v_user;

  update public.game_state
     set combo = v_new_combo,
         last_tap_at = v_time,
         last_batch_at = v_time
   where user_id = v_user;

  return jsonb_build_object(
    'ok', true,
    'coins', v_p.coins + v_gain,
    'coins_gained', v_gain,
    'total_taps', v_p.total_taps + v_taps,
    'taps_accepted', v_taps,
    'taps_rejected', p_tap_count - v_taps,
    'coins_per_tap', trunc(v_per_tap)::bigint,
    'level', v_level,
    'leveled_up', v_level > v_p.level,
    'experience', v_exp,
    'xp_to_next', public.xp_to_next(v_level),
    'combo', v_new_combo,
    'highest_combo', greatest(v_p.highest_combo, v_new_combo),
    'critical', v_crit_hit
  );
end;
$$;

-- 6.2 Buy an upgrade with earned coins. Atomic.
create or replace function public.purchase_upgrade(p_upgrade_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_p    public.profiles%rowtype;
  v_u    public.upgrades%rowtype;
  v_lvl  integer;
  v_cost bigint;
begin
  if v_user is null then
    raise exception 'Not authenticated' using errcode = '28000';
  end if;

  perform public.ensure_user_state(v_user);

  select * into v_u from public.upgrades where id = p_upgrade_id and active;
  if not found then
    raise exception 'Upgrade not found' using errcode = 'P0002';
  end if;

  select * into v_p from public.profiles where id = v_user for update;

  select coalesce(level, 0) into v_lvl
    from public.user_upgrades where user_id = v_user and upgrade_id = p_upgrade_id;
  v_lvl := coalesce(v_lvl, 0);

  if v_lvl >= v_u.max_level then
    raise exception 'Upgrade is already at max level' using errcode = '22023';
  end if;

  -- Cost of the NEXT level, computed server-side from the catalog.
  v_cost := greatest(1, trunc(v_u.base_cost * power(v_u.growth, greatest(v_lvl, 0))));

  if v_p.coins < v_cost then
    raise exception 'Not enough coins: need %, you have %', v_cost, v_p.coins
      using errcode = 'P0001', detail = json_build_object('reason', 'insufficient_coins', 'cost', v_cost, 'coins', v_p.coins)::text;
  end if;

  insert into public.user_upgrades (user_id, upgrade_id, level)
  values (v_user, p_upgrade_id, 1)
  on conflict (user_id, upgrade_id) do update set level = public.user_upgrades.level + 1, updated_at = now();

  update public.profiles set coins = coins - v_cost where id = v_user;

  return jsonb_build_object(
    'ok', true,
    'upgrade_id', p_upgrade_id,
    'level', v_lvl + 1,
    'max_level', v_u.max_level,
    'cost', v_cost,
    'coins', v_p.coins - v_cost
  );
end;
$$;

