create or replace function public.admin_adjust_coins(
  p_user_id uuid,
  p_delta   bigint,
  p_reason  text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_coins bigint;
begin
  perform public.require_admin();

  if abs(coalesce(p_delta, 0)) > 1000000000 then
    raise exception 'Delta out of allowed range' using errcode = '22023';
  end if;

  update public.profiles
     set coins = greatest(0, coins + coalesce(p_delta, 0))
   where id = p_user_id
  returning coins into v_coins;

  if v_coins is null then
    raise exception 'User not found' using errcode = 'P0002';
  end if;

  return jsonb_build_object('ok', true, 'coins', v_coins, 'reason', p_reason);
end;
$$;

create or replace function public.admin_set_admin(
  p_user_id uuid,
  p_role    text default 'admin',
  p_grant   boolean default true
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.require_admin();

  if p_user_id = auth.uid() and not coalesce(p_grant, false) then
    raise exception 'You cannot remove your own admin role' using errcode = '42501';
  end if;

  if coalesce(p_grant, false) then
    insert into public.admin_users (user_id, role) values (p_user_id, coalesce(p_role, 'admin'))
    on conflict (user_id) do update set role = excluded.role;
  else
    delete from public.admin_users where user_id = p_user_id;
  end if;

  return jsonb_build_object('ok', true);
end;
$$;

