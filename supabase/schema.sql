create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_base  text;
  v_name  text;
  v_try   integer := 0;
begin
  v_base := lower(coalesce(
    nullif(trim(new.raw_user_meta_data ->> 'username'), ''),
    nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
    'player'
  ));
  v_base := left(regexp_replace(v_base, '[^a-z0-9_]', '', 'g'), 20);
  if v_base = '' then
    v_base := 'player';
  end if;

  v_name := v_base;
  while exists (select 1 from public.profiles where lower(username) = v_name) and v_try < 8 loop
    v_name := v_base || '_' || substr(md5(gen_random_uuid()::text), 1, 4);
    v_try := v_try + 1;
  end loop;

  v_name := left(v_name, 24);

  insert into public.profiles (id, username, display_name)
  values (new.id, v_name, left(coalesce(nullif(trim(new.raw_user_meta_data ->> 'display_name'), ''), v_name), 40))
  on conflict (id) do nothing;

  insert into public.game_state (user_id) values (new.id) on conflict (user_id) do nothing;
  insert into public.daily_rewards (user_id) values (new.id) on conflict (user_id) do nothing;

  return new;
end;
$$;

